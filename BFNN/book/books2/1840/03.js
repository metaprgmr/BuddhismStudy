如是雖說三士，然於上士道第中亦能攝納餘二士道無所缺少，故彼二種是大乘道或分或支。《馬嗚阿闍黎》所造修世俗菩提心論云：「無害與諦實，與取及梵行，捨一切所執，此是善趣行。遍觀生死苦，斷故修諦道，斷除二種罪，此是寂靜行。亦應取此等，是出離道支。由達諸法空，生悲眾生流，無邊巧便行，是勝出離行。」是故此中非導令趣，唯以三有之樂，為所欲得下士夫道，及為自利唯脫生死為所欲得中士夫道，是將少許共彼二道作上士道引導前行，為修上士道之支分。

是故若發如前所說取心要欲，取心要之法，如中觀心論云：「誰不將無堅，如蕉沫之身，由行利他緣，修須彌堅實。上士具悲故，將剎那老死，病根本之身，為他安樂本。具正法炬時，斷八無暇暇，應以上士行，令其有果利。」謂應念云：我身無實，如蕉如沫，眾病巢穴，老等眾苦所出生處，應以上士所有現行度諸晝夜，令其不空而趣大乘。

苦爾理應先從上士引導，云何令修共下中耶？謂修此二所共之道，即上士道發起前行，此中道理後當宣說。

