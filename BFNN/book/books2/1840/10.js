辰三、布施自性所有差別

/KEPAN/辰一、總一切依當如何行

初中具六殊勝依殊勝者，依菩提心由此發起而行布施。物殊勝者，總諸施物無餘行施；若於別物而行施時，亦應不忘總施意樂。所為殊勝者，為令一切有情現前安樂究竟利義而正惠施。善巧方便殊勝者，經說無分別智之所攝持，初發業者當以通達法無性慧之所攝持。迴向殊勝者，迴向施善於大菩提。清淨殊勝者，攝大乘論說滅煩惱障及所知障。具足六種波羅蜜多者，如行法施，防止聲聞、獨覺作意，是名持戒，於種智法信行堪忍，忍恕他罵，為令法施倍復增長，發起欲樂是名精進；心專一趣，不雜小乘，迴向此善於大菩提，是名靜慮；了知能施、所施、受者悉如幻化，是名般若；具足六種力最強大，此是八千頌廣釋所說。

/KEPAN/辰二、觀待別依所有差別

第二者，總之經說在家菩薩應修財施，出家菩薩應行法施。菩薩別解脫經云：「《舍利子》！若有在家菩薩以七珍寶充滿殫伽沙數諸佛國土供養如來、應正等覺。《舍利子》！若有出家菩薩開示宣說一四句頌，此所生福極多於彼。《舍利子》！如來未許出家菩薩修諸財施。」集學論說此中密意障礙聞等謂遮出家特集財寶而行布施，若無妨害自善所作，由宿福力多所獲得，當行財施。《霞惹瓦》云：「我不為汝說施功德，我是宣說攝持過患」，是於出家辛勤追求集積財寶而行布施，令其淨戒多生瘡尤不喜之語。

