律咒二中，若先未受各各律儀，不可聽聞所有學處。此不同彼，此諸學處先當善知淨修相續，次樂受者，乃可授與諸律儀故。如菩薩地云：「欲受菩薩淨戒律儀，先應為說菩薩法藏摩怛履迦。其中所說菩薩學處及犯處相，若慧觀察自思擇已至心愛樂，非為他勸，非為勝他，當知是名堅固菩薩，堪受菩薩淨戒律儀。如受戒法，彼亦應受，亦應授彼。」故先了知諸所學處為作意境，若於學處至心愛樂修欲學已，次受律儀則極堅固，是善方便。此及下文二處宣說，文恐太繁，當於後釋。

