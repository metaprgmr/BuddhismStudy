六、大勢名稱者，有大名稱，有大美譽，謂於惠施具足勇健精進等德，由此因緣，為諸大眾所供養處。

七、丈夫性者，謂成就男根。

八、大力具足者，謂由宿業力，為性少病或全無病，於現法緣，起大勇悍。此復第一謂住樂趣，第二謂身，第三謂生，第四謂財位僚屬，第五謂為世間量則，第六謂彼所有名稱，七謂一切功德之器，第八謂於諸所應作勢力具足。

