欲邪行事者。略有四種，謂：所不應行、非支、非處及以非時。此中初者，謂行不應行所有婦女及一切男、非男、非女。此之初者，攝分中云：「若於母等、母等所護，如經廣說名不應行」，如《馬鳴阿闍黎說此義》云：「言行應行者，他攝具法幢、種護至王護、他已娶娼妓、諸親及繫屬，此是不應行。」他所攝者，謂他妻妾。具法幢者，謂出家女。種姓護者，謂未適嫁，父母等親或大公姑或守門者，或雖無此自己守護。若王若敕而守護者，謂於其人制治罰律。於他已給價金娼妓，說為邪行，顯自給價非欲邪行。《大依怙尊》亦作是說。男者俱通自他。非支分者，謂除產門所有餘分，《馬鳴阿闍黎》云：「云何名非支，口便道嬰童，腿逼及手動。」《大依怙》云：「言非支者，謂口穢道及童男女前後孔戶并其自手。」此說亦同。非處所者，謂諸尊重所集會處，若塔廟處、若大眾前、若於其境有妨害處，謂地高下及堅硬等。《馬鳴阿闍黎》云：「此中處境者，在法塔像等菩薩居處等，親教及軌範井在父母前，非境不應行。」《大依怙》師─亦如是說。非其時者，謂穢下降胎滿孕婦、若飲兒乳、若受齋戒、若有疾病，匪宜習故，若道量行量謂極至經於五返。《馬鳴阿闍黎》云：「此中非時者，穢下及孕婦，有兒非欲解，及其苦憂等，住八支非時。」《大依怙尊》亦復同此，稍差別者，謂晝日時亦名非時。非支等三，雖於自妻尚成邪行，況於他所！意樂分三：想者攝分中說，於彼彼想是須無誤。《毗奈耶》中於不淨行他勝處時，說想若錯不錯皆同。俱舍釋說作自妻想而趣他妻，不成業道。若於他妻作餘妻想而趣行者，有二家計，謂成不成。煩惱者，三毒隨一。等起者，謂樂欲行諸不淨行。加行者，攝分中說教他邪行，教者亦生欲邪行罪；俱舍釋說如此則無根本業道。前或意非根本罪，然須觀察。究竟者，謂兩兩交會。

妄語事者。謂見、聞、覺、知四及此相違四。能解之境，謂他領義。意樂分三：想者謂於所見變想，不見及於未見變想見等，煩惱者，謂三毒；等起者，謂覆藏想樂說之欲。加行者，謂或言說或默忍受或現身相，此復所求或為自利或為利他，隨為何故說悉同犯。此中說於妄語離間及粗惡語，雖教他說，其三亦成。俱舍本釋於語四業皆說教他亦成業道，毗奈耶中說起此等究竟犯時，要須自說。究竟者，謂他領解。俱舍釋說若他未解，僅成綺語；離間粗語，亦皆同此。

離間語事者。謂諸有情或和不和。意樂分三：想及煩惱如前；等起者，和順有情樂乖離欲，不和有情樂不合欲。加行者，隨以實語，若非實語；隨說所說，若美不美；隨其所求為自為他而有陳說。究竟者，攝分中云：「究竟者，謂所破領解。」謂他了解所說離言。

粗惡語事者。謂諸有情能引恚惱。意樂中想、煩惱如前；等起者，謂樂粗言欲。加行者，謂以若實，若非實語；或依種過或依身過，或依業過，或依戒過，或依現行所有過失說非愛語。究竟者，攝分中說：「究竟者謂呵罵彼」，俱舍釋說須所說境解所說義。

綺語事者。謂能引發無利之義。意樂中三：想者雖僅說為於彼彼想，然於此中，是即於其所欲說義彼想而說，此中不須能解境故；煩惱者，謂三毒隨一；等起者，謂樂宣說無屬亂語。加行者，謂發勤勇宣說綺語。究竟者，謂纔說綺語，此復七事相應，謂：若宣說鬥訟競諍、若於外論或梵志咒以愛樂心受持諷頌、若苦逼語如傷嘆等、若戲笑遊樂受欲等語、若樂處眾宣說王論臣論國論盜賊論等、若說醉語及顛狂語、若邪命語。語無係屬，無法相應，非義相應者，謂前後語無所連續，若說雜染、若歌笑等、若觀舞時而發言詞。前三語過，是否綺語？雖有二家，然此所說順於前家。

貪欲事者。謂屬他財產。意樂分三：想者謂於彼事作彼事想；煩惱者，謂三毒隨一；等起者，謂欲令屬我。加行者，謂於所思義正發進趣。究竟者，說於彼事定期屬己，謂念其財等願成我有。此中貪心圓滿，須具五相：一有耽著心，謂於自財所；二有貪婪心，謂樂積財物；三有饕餮心，謂於屬他資財等事，計為華好深生愛味；四有謀略心，謂作是念：凡彼所有何當屬我；五有覆蔽心，謂由貪欲不覺羞恥，不知過患及與出離。若此五心，隨缺一種貪欲心相即非圓滿。瑜伽師地論中，於十不善俱說加行。又非圓滿貪欲之理者，謂作是念云：「何當能令其家主成我僕使，如我所欲？」又於其妻子等及飲食等諸資身具，亦如是思。又作是念云：「何當能令他知我少欲、遠離、勇猛精進、具足多聞、成施性等？」又作是念云：「何當能令諸國王及諸商王、四眾弟子，供事於我得衣食等？」又作是念，起如是欲，云：「何令我當生天上，天妙五欲以為遊戲，當生猛利遍入世界，乃至願生他化自在？」又於父母、妻子、僕等同梵行者所有資具，發欲得者，亦是貪欲。

瞋恚心中。事、想、煩惱如粗惡語。等起者，樂打等欲，云何令其遭殺遭縛，若由他緣或自任運耗失敗產。加行者，即於所思而起加行。究竟者，謂於打等期心決定或已斷決。此亦有五；全則圓滿，缺則非圓─謂具五心：一有憎惡心，謂於能損害相，隨法分別故；二有不堪耐心，謂於不饒益不堪忍故；三有怨恨心，謂於不饒益數數非理思惟隨念故；四有謀略心，謂作是念；何當捶撻，何當殺害；五有覆蔽心，謂於瞋恚不覺羞恥、不知過患及與出離僅成損害心者，謂作是念：「彼於我所已作、正作諸無義事，故我於彼當作無義。」盡其所有幾許思惟，爾許一切皆損害心。如是願他現法喪失親屬、資財及善法等，及願後法往惡趣中，亦是損心。

邪見事者。謂實有義。意樂分三：想者謂於所謗義作諦實想；煩惱者謂三毒隨一；等起者謂樂誹謗欲；加行者，即於所思策發加行。此復有四，謂：謗因果、作用、有事。誹謗因者，謂云無有妙惡行等。誹謗果者，謂云無有彼二異熟。誹謗作用分三：誹謗殖種、持種作用者，謂云無有若父若母；誹謗往來作用者，謂云無有前世後世；誹謗受生作用者，謂云無有化生有情。謗實有事者，謂云無有阿羅漢等。究竟者，謂誹謗決定。此亦由於五相圓滿─謂具五心：一有愚昧心，謂不如實了所知故；二有暴酷心，謂樂作惡故；三有越流行心，謂於諸法不如正理善觀察故；四有失壞心，謂謗無布施愛養祠祀妙行等故；五有覆蔽心，謂由邪見不覺羞恥、不知過患及與出離故。此五若缺，則不圓滿。雖其邪見復有所餘，然唯說此名邪見者，由此能斷一切善根，隨順諸惡隨意所行，是為一切邪見之中極重者故。其中殺生、粗語、瞋心由三毒起，由瞋究竟。不與而取、邪行、貪欲，由三毒起唯貪究竟。妄言、離間及諸綺語發起究竟，俱由三毒。邪見由其三毒發起，唯癡究竟。此等之中，思唯是業而非業道，身語所有七支是業亦是業道，思行處故。貪欲等三業道非業。

