第二、兼略開示具力業門分四：由福田門故力大者。謂於三寶尊重似尊父母等所，於此雖無猛利意樂，略作損益能得大福及大罪故。此復猶如念住經云：「從佛法僧雖取少許亦成重大。若不與取佛法僧物，仍以彼等同類奉還。盜佛法即得清淨，盜僧伽者乃至未受不得清淨，福田重故。若盜食物，當墮有情大那落迦；若非食物，則當生於諸獄間隙，無間近邊極黑暗處。」日藏經中特說犯戒受用僧物少許，或葉或華或果，當生有情大那落迦；設經長夜而得脫離，復當生於曠野尸林無手乏足諸旁生類及無手足盲餓鬼中，經歷多年恆受苦等極大過患。又說已施僧眾苾芻，雖諸華等自不應用、不應轉與諸居家者；諸居家者，不應受用；罪亦極重。即前經云：「寧以諸利劍，割斷自支體，已施僧伽物，不與在家者。寧食熱鐵丸，火燄即熾猛，不應於僧中，受用僧伽業。寧取食猛火，量等須迷盧，不以居家身，受用僧財物。寧破一切體，貫諸大弗上，不以居家身，受用僧財物。寧入諸舍宅，火炭遍充滿，不以居家身，夜宿僧房舍。」又僧伽中，若諸菩薩補特伽羅，是極大力善不善田。能入發生信力契印經說：「設如有一由忿恚故，禁閉十方一切有情於黑暗獄。若有忿恚背菩薩住，云不瞻視此暴惡者，較前生罪極無數量。又較劫奪南瞻部洲一切有情一切財物，若有輕毀隨一菩薩，亦如前說。又較焚毀殫伽沙數諸佛塔廟，若於勝解大乘菩薩起損害心，發生瞋恚，說諸惡稱，亦如前說。」能入定不定契印經說：「若剜十方有情眼目，由慈心故令眼還生及將前說一切有情，放出牢獄，悉皆安立轉輪王樂或梵天樂。如次若於諸能勝解大乘菩薩淨信瞻視，及由淨信樂欲瞻視，稱揚讚歎，較前生福極無數量。」極善寂靜決定神變經中亦說：「較諸殺害《南贍部洲》一切有情，或盡劫奪一切財產，若於菩薩所修善行，下至摶食施諸旁生而作障難，能生無量罪。」故於是處，極應防慎。

由所依門故力大者。謂如鐵丸小亦沈水，即彼成器雖大上浮，說智不智所作罪惡而有輕重。此因相者，涅槃經說諸愚癡者，如蠅粘涕不能脫離，雖於小罪不能脫離。由無悔心不能善行，由覆藏過，雖先有善為惡染污，故應現受異熟之因，變為極重那落迦因。又如少水投鹽一掬，則難飲用，或如欠他一文金錢不能還償，漸被逼縛受諸苦腦。又說五相雖是當感現輕異熟，能令熟於那落迦中，謂：重愚癡、善根微薄、惡業尤重、不起追悔、先無善行。故說輕微是指智者能悔前失、防護後過、不藏諸惡、勤修善法諸惡對治。若不修此，妄矜為智，由輕懵門，知而故行，是為尤重。寶蘊經亦說：「三千所有一切有情，皆入大乘，具輪王位，各以燈燭器等大海，炷如須彌，供養佛塔，其福不及出家菩薩，於小燈燭塗以油脂，持供塔前，所得福德百分之一。」此中意樂謂菩提心及其福田俱無差別，然所供物殊異極大，是所依力極為明顯。

由是道理，則無律儀與有律儀，同是有中，具一具二具三之身，修行道時，顯然後後較於前前進趣優勝。如諸在家修施等時，受持齋戒律儀而修，與無律儀所修善根，勢力大小亦極明顯制罰犯戒經說較諸世人具十不善，經百歲中恆無間缺所集眾惡，若有比丘毀犯尸羅，仙幢覆身經一日夜，受用信施，不善極多，亦是由其所依門中，罪惡力大。《分辨阿笈摩》亦云：「寧吞熱鐵丸，猛燄極可畏，不以犯戒身，受用國人食。」通說犯戒及綏學處。《敦巴仁波卿》云：「較依正法所起罪惡，十種不善是極少惡。」現見實爾。

由事物門故力大者。施有情中，正法布施，供養佛中，正行供養，較諸財施、財物供養最為超勝。此是一例，餘皆應知。

由意樂門故力大者。寶蘊經說較三千界一切有情各建佛塔，量等須彌，於此諸塔，復經微塵沙數之劫，以一切種可供養事，承事供養；若諸菩薩不離一切智心，僅散一華，其福極多。如是由其攀緣所得，若有勝劣及緣自他利益事等意樂差別，此復由其強盛、微弱、恆促等門，應當了知。又於惡行，若煩惱心，猛利恆長，其力則大；其中復以瞋力為大。入行論云：「千劫所集施，供養善逝等，此一切善行，一恚能摧壞。」此復若瞋同梵行者及瞋菩薩，較前尤重。三摩地王經云：「若互相瞋恚，非戒聞能救，非定非蘭若，施供佛能救。」入行論中亦云：「如此勝子施主所，設若有發暴惡心，能仁說如惡心數，當住地獄經爾劫。」

/KEPAN/寅三、此等之果

第三、其果分三：異熟果者。謂十業道，一一皆依事及三毒上中下品，有三三等。本地分說此中上品殺生等十，一一能感生那落迦，中十、一一感生餓鬼，下十、一一能感旁生。


十地經說中下二果與此相違。

等流果者。謂出惡趣，次生人中，如其次第，壽量短促，資財匱乏，妻不貞良，多遭誹謗，親友乖離，聞違意聲，言不威肅，貪瞋癡三，上品猛利。諦者品及十地經中，於其一一說二二果，謂：「設生人中，壽量短促，多諸疾病。資財匱乏，與他共財，眷屬不調，或非可信。妻有匹偶。多遭誹謗，受他欺誑。眷屬不和，眷屬鄙惡。聞違意聲，語成鬥端，語不尊嚴，或非堪受，無定辯才。貪欲重大，不知喜足；尋求無利，或不求利。損害於他，或遭他害；見解惡鄙，諂誑為性。」諸先尊長說縱生人中，愛樂殺生等事，是造作等流果。前所說者，是領受等流果。

諸主上果或增上果者。謂由殺生，能感外器世間所有飲食及藥果等皆少光澤，勢力、異熟及與威德並皆微劣，難於消變，生長疾病。由此因緣，無量有情，未盡壽量而便中夭。不與取者，謂眾果渺少，果不滋長，果多變壞，果不貞實；多無雨澤，雨多淋澇，果多乾枯及全無果。欲邪行者，謂多便穢、泥糞不淨，臭惡迫迕，不可愛樂。虛妄語者，謂農作、行船事業邊際，不甚滋息，不相諧偶，多相欺惑，饒諸怖畏、恐懼因緣。離間語者，謂其地處丘坑間隔、險阻難行，饒諸怖畏、恐懼因緣。粗惡語者，謂其地所多諸株杌、刺石礫瓦，枯槁無潤，無有池沼、河流泉湧，乾地鹵田，丘陵坑險，饒諸怖畏、恐懼因緣。諸綺語者，謂諸果樹不結果實，非時結實，時不結實，未熟似熟，根不堅牢，勢不久停，園林池沼可樂極少，饒諸怖畏、恐懼因緣。貪欲心者，謂一切盛事經歷一一年時月日，漸漸衰微，唯減無增。瞋恚心者，謂多疫癘、災橫擾惱、怨敵驚怖、獅子虎等、蟒蛇蝮蠍、蚰蜒百足、毒暴藥叉諸惡賊等。諸邪見者，謂器世間所有第一勝妙生源悉皆隱沒，諸不淨物乍似清淨，諸苦惱物乍似安樂，非安居所、非救護所、非歸依所。

/KEPAN/丑二、白業果

思惟白業果分二：

寅一、白業
寅二、果

/KEPAN/寅一、白業

本地分說，於殺生、不與取、欲、邪行，起過患欲解，起勝善心；若於彼起靜息方便及於彼靜息究竟中所有身業。語四意三，亦皆如是。其差別者，謂云語業及云意業，事及意樂、加行、究竟，如應配合。例如遠離殺生業道事者，謂他有情。意樂者，謂見過患，起遠離欲。加行者，謂起諸行靜息殺害。究竟者，謂正靜息圓滿身業。以此道理，餘亦應知。

/KEPAN/寅二、果

果中有三：異熟者，謂由軟中上品善業，感生人中、欲界天中、上二界天。諸等流果及增上果，違於不善，如理應知。十地經說，以此十種，怖畏生死，離諸悲心，由隨順他言教修習，辦聲聞果。又諸無悲，不依止他，欲自覺悟，善修緣起，辦獨勝果。若心廣大，具足悲心，善權方便，廣發宏願，終不棄捨一切有情，於極廣大諸佛智慧，緣慮修習，成辦菩薩一切諸地波羅密多。由善修習此一切種，則能成辦一切佛法。如是二聚十種業道及彼諸果，凡餘教典未明說者，一切皆是如本地分、攝抉擇分意趣而說。

第三、顯示餘業差別中，引滿差別者，引樂趣業是諸善法，引惡趣業是諸不善。諸能滿者，則無決定。於樂趣中，亦有斷支、關節殘根、顏貌醜陋、短壽多疾、匱乏財等是不善作。於諸旁生及餓鬼中，亦有富樂極圓滿者，是善所作。由如是故共成四句，謂於能引善所引中，有由能滿善所圓滿及由不善圓滿二類；於諸能引不善引中，有由能滿不善圓滿及由善法圓滿二類。集論云：「應知善不善業，是能牽引及能圓滿，於善惡趣受生之業；能牽引者謂能引異熟；能圓滿者謂既生已，能令領納愛與非愛。」俱舍論云：「由一引一生，能滿則眾多。」謂由一業能引一生，非能引多，亦非眾多共引一生；諸能滿中則有眾多。集論則說頗有諸業，唯由一業牽引一生；又有諸業，唯由一業牽引多生；頗有諸業，由眾多業牽引一生；亦有諸業，由眾多業牽引多生。釋中說云：「有由一剎那業，唯能長養一世異熟種子，及由彼業而能長養多世異熟種子。有由多剎那業，唯能數數長養一世種子，及由眾多互相觀待，而能數數長養展轉多生種子。」

定不定受業者。如本地分云：「順定受業者，謂故思已，若作若增長業。順不定受業者，謂故思已，作而不增長業。」作與增長所有差別者，即前論云：「云何作業？謂若思業或思惟已，身語所起。」又云：「增長業者，除十種業，謂─一、夢所作；二、無知所作；三、無故思所作；四、不利不數所作；五、狂亂所作；六、失念所作；七、非樂欲所作；八、自性無記；九、悔所損害；十、對治所損除此十種業所餘諸業。不增長業者，謂即所說十種。」攝抉擇分亦說四句：一、作殺生而非增長，謂：無識別所作、夢中所作、非故思作、自無樂欲他逼令作。若有暫作，續即發起猛利追悔及厭患心，懇責厭離正受律儀，令彼薄弱未與異熟，便起世間所有離欲損彼種子，及起出世永斷之道害彼種子。二、增長而非作者，為害生故，於長夜中，數隨尋伺，然未殺生。三、作而增長者，謂除前二句一切殺生。四、非作非增長者，謂除前三，從不與取乃至綺語，隨其所應如殺應知。於意三中，無第二句；於初句中，亦無不思而作他逼令作。

決定受中，依受果時分三：其中現法受者，謂即彼果現法成熟。本地分說此復有八，若由增上顧戀意樂顧戀其身、財物諸有，造作不善，於現法受。若由增上不顧意樂，不顧彼等，作諸善法；如是若於諸有情所增上損惱、增上慈悲；又於三寶尊重等所增上憎害，及於此所增上淨信勝解意樂；又於父母諸尊重等恩造之所，由增上品，酷暴背恩，所有意樂，所作不善，於現法受。若由增上報恩意樂所作善法，於現法受。順生受者，謂於二生當受其果。順後受者，謂於三世以後成熟。於相續中，現有眾多善、不善業成熟理者，謂諸重業即先成熟。輕重若等，於臨終時，何者現前，彼即先熟。若此亦等，則何增上多串習者。若此復等，則先所作，彼則先熟。如俱舍釋所引頌云：「諸業於生死，隨重近串習，隨先作其中，即前前成熟」。

