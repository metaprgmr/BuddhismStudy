初中有五：例如殺生，由意樂故重者，謂猛利三毒所作。由加行故重者，謂：或已殺生或正，或當具歡喜心、具踴躍心、或有自作或復勸他，於彼所作稱揚讚歎，見同行者意便欣慶。由其長時思量積蓄怨恨心已，方有所作、無間所作、殷重所作；或於一時頓殺多生，或令發起猛利痛苦而行殺害，或令怖畏、作不應作而後殺害，若於孤苦貧窮、哀慼悲泣等者而行殺害。由無法故重者，謂不能日日乃至極少時持一學處，或亦不能半月、八日、十四、十五受持齋戒，於時時間惠施修福、問訊禮拜、迎送合掌和敬業等，又亦不能於時時間獲得增上慚愧惡作，又不能證世間離欲或法現觀。由邪執故重者，謂由依於作邪祠祀，所有邪見執為正法而行殺戮，又作是心─畜等乃是世主所化為資具故，雖殺無罪─諸如是等，依止邪見而行殺害。由事故重者，謂若殺害大身傍生、人或人相父母、兄弟、尊長、委信、有學、菩薩、羅漢、獨覺及知如來不能殺害，而以惡心出其身血。違此五因，為輕殺生。

餘九除事，如其殺生，輕重應知。由其事故重不與取者，謂若劫盜眾多上妙及委信者，劫盜孤貧出家之眾及此法眾；若入聚落而行劫盜，若劫有學、羅漢、獨覺、僧伽佛塔所有財物。由其事故重邪行者，謂行不應行中，若母母親，委信他妻，或比丘尼，或正學女，或勤策女。非支行中謂於面門。非時行中，謂受齋戒，或胎圓滿，或有重病。非處行中，謂塔近邊，若僧伽藍。由其事故重妄語者，謂為誑惑多取他財而說妄語。若於父母乃至於佛，若於善賢，若於知友而說妄語。若能起重殺生等三而說妄語；為破僧故而說妄語─於一切中，此為最重。由其事故重離間語者，謂破壞他長時親愛及善知識父母男女。若能破僧，若能引發身三重業所有離間語。由其事故重粗惡語者，謂於父母等及餘尊長說粗惡語，若以非真非實妄語說粗惡語，現前毀罵，訶責於他。由其事故重綺語者，妄語等三，所有綺語，輕重如前。若諸依於鬥訟諍競所有綺語，若以染心於外典籍而讀誦等。若於父母親屬尊重，調弄輕笑，現作語言，不近道理。由其事故重貪欲者，謂若貪欲僧伽、佛塔、所有財寶，及於已德增上慢，乃於王等及諸聰睿同梵行所起增上欲，貪求利敬。由其事故重瞋恚者，謂於父母親屬尊長，無過貧苦諸可哀愍、諸誠心悔所作過者，起損害心。由其事故重邪見者，謂能轉趣謗一切事，較餘邪見此為最重。又謂世間無阿羅漢，正至正行，此見亦爾。與上相違是輕應知。

本地分中說有六相，成極尤重。加行故者，謂由猛利三毒，或由猛利無彼三毒發起諸業。串習故者，謂於長夜親近修習，若多修習善惡二業。自性故者，謂屬身語七支，前前重於後後；屬意三支，後後重於前前。事故者，謂於佛法僧諸尊重，所為損為益。所治一類故者，謂乃至壽存，一向受行諸不善業，未曾一次受行善法。所法損害故者，謂永斷除諸不善品，令諸善業離欲清淨。親友書中亦云：「無間貪著無對治，從德尊事所起業，是五重大善不善，其中應勤修善行。」其三寶等為具德事，其父母等為有恩事，開二成立。

